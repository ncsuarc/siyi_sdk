"""Generate the TypeScript client's command types from the remote command registry.

Writes ``clients/typescript/src/generated.ts``: every SDK enum and model the camera
service can send or accept, and the parameters and result of each passthrough
command. Run it after changing ``siyi_sdk.models`` or ``siyi_sdk.remote.registry``;
``tests/remote/test_ts_types.py`` fails while the file is out of date.

    python scripts/generate_ts_types.py
"""

from __future__ import annotations

import dataclasses
import enum
import ipaddress
import types
import typing
from pathlib import Path
from typing import Any, Final

from siyi_sdk.client import SIYIClient
from siyi_sdk.models import FunctionFeedback
from siyi_sdk.remote import registry
from siyi_sdk.remote.lock_config import LockConfig

OUTPUT: Final = (
    Path(__file__).resolve().parents[1] / "clients" / "typescript" / "src" / "generated.ts"
)

_HEADER: Final = """\
// Generated by scripts/generate_ts_types.py from siyi_sdk.models and
// siyi_sdk.remote.registry. Do not edit by hand.

/* eslint-disable */
"""


class _Collector:
    """Turns Python annotations into TypeScript, remembering the models it meets."""

    def __init__(self) -> None:
        self.enums: dict[str, type[enum.IntEnum]] = {}
        self.models: dict[str, type[Any]] = {}

    def ts(self, annotation: Any) -> str:  # noqa: ANN401 - any annotation
        if annotation is type(None):
            return "null"
        if annotation is bool:
            return "boolean"
        if annotation in (int, float):
            return "number"
        if annotation is str or annotation is ipaddress.IPv4Address:
            return "string"
        if annotation is bytes:
            return "Uint8Array"
        if isinstance(annotation, type) and issubclass(annotation, enum.IntEnum):
            self.enums[annotation.__name__] = annotation
            return annotation.__name__
        if dataclasses.is_dataclass(annotation) and isinstance(annotation, type):
            if annotation.__name__ not in self.models:
                self.models[annotation.__name__] = annotation
                for hint in typing.get_type_hints(annotation).values():
                    self.ts(hint)
            return annotation.__name__
        origin = typing.get_origin(annotation)
        args = typing.get_args(annotation)
        if origin is typing.Literal:
            return " | ".join(_literal(a) for a in args)
        if origin in (typing.Union, types.UnionType):
            return " | ".join(self.ts(a) for a in args)
        if origin is tuple:
            return "[" + ", ".join(self.ts(a) for a in args) + "]"
        if origin is list:
            return f"{self.ts(args[0])}[]"
        if origin is dict:
            return f"Record<string, {self.ts(args[1])}>"
        raise TypeError(f"No TypeScript mapping for {annotation!r}")


def _literal(value: object) -> str:
    return f'"{value}"' if isinstance(value, str) else str(value).lower()


def render() -> str:
    """The full contents of ``generated.ts``."""
    collector = _Collector()
    commands: list[str] = []
    for name, command in registry.REMOTE_COMMANDS.items():
        hints = typing.get_type_hints(getattr(SIYIClient, name))
        params: list[str] = []
        for field_name, field in command.input_model.model_fields.items():
            optional = "?" if not field.is_required() else ""
            params.append(f"{field_name}{optional}: {collector.ts(hints[field_name])}")
        if command.confirmation:
            params.append("confirm: true")
        result = collector.ts(hints["return"])
        body = "{ " + "; ".join(params) + " }" if params else "Record<string, never>"
        commands.append(f"  {name}: {{ params: {body}; result: {result} }};")

    # Sent outside the passthrough commands: feedback events and lock settings.
    collector.ts(FunctionFeedback)
    collector.ts(LockConfig)

    out = [_HEADER]
    for name, enum_type in sorted(collector.enums.items()):
        members = ", ".join(f"{m.name}: {m.value}" for m in enum_type)
        out.append(f"export const {name} = {{ {members} }} as const;")
        out.append(f"export type {name} = (typeof {name})[keyof typeof {name}];\n")

    for name, model in sorted(collector.models.items()):
        hints = typing.get_type_hints(model)
        fields = "".join(
            f"  {f.name}: {collector.ts(hints[f.name])};\n" for f in dataclasses.fields(model)
        )
        out.append(f"export interface {name} {{\n{fields}}}\n")

    out.append("/** Camera commands the service passes through to SIYIClient. */")
    out.append("export interface CameraCommands {")
    out.extend(commands)
    out.append("}\n")

    read_only = sorted(n for n, c in registry.REMOTE_COMMANDS.items() if c.read_only)
    out.append("/** Commands observers may call; the rest need control. */")
    out.append("export const READ_ONLY_COMMANDS: ReadonlySet<keyof CameraCommands> = new Set([")
    out.extend(f'  "{n}",' for n in read_only)
    out.append("]);")
    return "\n".join(out) + "\n"


def main() -> None:
    """Write ``generated.ts``."""
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
